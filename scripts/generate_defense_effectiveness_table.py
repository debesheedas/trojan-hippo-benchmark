#!/usr/bin/env python3
"""Generate CCS_thesis_manuscript/tables/defense_effectiveness_test_100.tex from attack consolidated CSVs."""

import csv
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ATTACK = REPO / "data/benchmark/consolidated_attack_results"
OUT = REPO / "CCS_thesis_manuscript/tables/defense_effectiveness_test_100.tex"

BACKENDS = ["No Memory", "Explicit", "Mem0", "RAG", "Context"]
DEFENSES_CSV = [
    "None",
    "User Prompt Only",
    "No Untrusted Tools",
    "Limit Memory Length",
    "Provable Policy",
]
DEFENSE_TEX = [
    "None",
    "User-prompt-only",
    "No-untrusted-tools",
    "Limit-memory-length",
    "Provable policy",
]
MODELS = [
    ("gemini-3.1-pro-preview", "Gemini 3.1 Pro Preview"),
    ("gpt-5-mini", "GPT-5-mini"),
]


def parse_cell(s: str):
    s = (s or "").strip()
    if not s or s == "-" or s.upper() == "ERR":
        return None
    s = s.rstrip("%").strip()
    try:
        return float(s)
    except ValueError:
        return None


def fmt_utility(v):
    if v is None:
        return "---"
    return f"{v:.1f}"


def fmt_asr_tex(v):
    if v is None:
        return "---"
    s = f"{v:.1f}"
    if v < 10:
        return f"\\asrcell{{{s}}}"
    if v < 50:
        return f"\\asrcellmed{{{s}}}"
    return f"\\asrcellhigh{{{s}}}"


def load_metric_rows(csv_path: Path) -> dict:
    """defense -> {'Utility': [...5], 'Attack (Total)': [...5]}"""
    out: dict[str, dict[str, list]] = {d: {} for d in DEFENSES_CSV}
    with open(csv_path, encoding="utf-8") as f:
        r = csv.DictReader(f)
        rows = list(r)
    for row in rows:
        d = row.get("Defense Type", "").strip()
        if d not in out:
            continue
        metric = (row.get("Metric") or "").strip()
        metric_norm = re.sub(r"\s+", "", metric)
        metric_key = None
        if metric_norm == "Utility":
            metric_key = "Utility"
        elif metric_norm == "Attack(Total)":
            metric_key = "Attack (Total)"
        if not metric_key:
            continue
        vals = []
        for b in BACKENDS:
            col = f"{b} (%)"
            raw = row.get(col, "-")
            vals.append(parse_cell(raw))
        out[d][metric_key] = vals
    return out


def model_block(display_name: str, data: dict) -> list[str]:
    lines = [
        rf"\multicolumn{{11}}{{l}}{{\textbf{{{display_name}}}}} \\",
        r"\hline",
        r"& \multicolumn{5}{c|}{\textbf{Utility under attack}} & \multicolumn{5}{c}{\textbf{ASR}} \\",
        r"\textbf{Defense} & No Mem. & Explicit & Mem0 & RAG & Context & No Mem. & Explicit & Mem0 & RAG & Context \\",
        r"\hline",
    ]
    for d_csv, d_tex in zip(DEFENSES_CSV, DEFENSE_TEX):
        u = data.get(d_csv, {}).get("Utility", [None] * 5)
        a = data.get(d_csv, {}).get("Attack (Total)", [None] * 5)
        util_cells = [fmt_utility(u[i] if i < len(u) else None) for i in range(5)]
        asr_cells = [fmt_asr_tex(a[i] if i < len(a) else None) for i in range(5)]
        lines.append(
            f"{d_tex} & "
            + " & ".join(util_cells)
            + " & "
            + " & ".join(asr_cells)
            + r" \\"
        )
    lines.append(r"\hline")
    return lines


def main() -> int:
    blocks = []
    for model_dir, display in MODELS:
        p = ATTACK / model_dir / "test_100" / "average_summary.csv"
        if not p.exists():
            print(f"Missing {p}", file=sys.stderr)
            return 1
        data = load_metric_rows(p)
        blocks.append(model_block(display, data))

    lines = [
        "% Auto-generated by scripts/generate_defense_effectiveness_table.py",
        "% Defense effectiveness at test_100: Utility under attack and ASR by defense and memory backend.",
        r"\newcommand{\asrcell}[1]{\cellcolor{green!12}#1}",
        r"\newcommand{\asrcellmed}[1]{\cellcolor{yellow!10}#1}",
        r"\newcommand{\asrcellhigh}[1]{\cellcolor{red!12}#1}",
        "",
        r"\begin{table*}[h]",
        r"\centering",
        r"\small",
        r"\caption{Trigger session $N=100$: utility under attack and attack success rate (ASR) by defense and memory backend, for Gemini~3.1~Pro~Preview and GPT-5-mini. All values in \%. ``---'' denotes not applicable or missing. ASR cells are lightly shaded (low to high).}",
        r"\label{tab:defense-effectiveness-test100}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{l|ccccc|ccccc}",
        r"\hline",
    ]
    lines.extend(blocks[0])
    lines.extend(blocks[1])
    lines.extend(
        [
            r"\end{tabular}",
            r"}%",
            r"\end{table*}",
            "",
        ]
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
