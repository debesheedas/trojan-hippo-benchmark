#!/usr/bin/env python3
"""Generate appendix LaTeX tables for ASR by topic at test_100 from consolidated CSVs."""

import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BASE = REPO / "data/benchmark/consolidated_attack_results"
OUT = REPO / "CCS_thesis_manuscript/tables"
TOPICS = ["finance", "health", "legal", "tax", "identity"]
DEFENSES = [
    "None",
    "User Prompt Only",
    "No Untrusted Tools",
    "Limit Memory Length",
    "Provable Policy",
]
COLS = ["No Memory (%)", "Explicit (%)", "Mem0 (%)", "RAG (%)", "Context (%)"]
DEFENSE_TEX = [
    "None",
    "User-prompt-only",
    "No-untrusted-tools",
    "Limit-memory-length",
    "Provable policy",
]


def parse_pct(s: str):
    s = (s or "").strip()
    if s in ("-", "", "ERR"):
        return None
    s = s.rstrip("%").strip()
    try:
        return float(s)
    except ValueError:
        return None


def load_topic(model_dir: str, topic: str) -> dict:
    path = BASE / model_dir / "test_100" / f"{topic}_test_100_consolidated.csv"
    rows = {}
    with open(path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["Metric"] != "Attack (Total)":
                continue
            rows[row["Defense Type"]] = [parse_pct(row[c]) for c in COLS]
    return rows


def shade(v):
    if v is None:
        return "---"
    if v < 10:
        return f"\\asrcellTopicA{{{v:g}}}"
    if v < 50:
        return f"\\asrcellTopicB{{{v:g}}}"
    return f"\\asrcellTopicC{{{v:g}}}"


def row_cells(data_by_topic: dict, defense: str) -> str:
    parts = []
    for bi in range(5):
        for topic in TOPICS:
            row = data_by_topic.get(topic, {}).get(defense)
            val = row[bi] if row and bi < len(row) else None
            parts.append(shade(val))
    return " & ".join(parts)


def write_table(model_dir: str, caption: str, fname: str, label: str) -> None:
    data_by_topic = {t: load_topic(model_dir, t) for t in TOPICS}
    lines = [
        "% Auto-generated by scripts/generate_asr_by_topic_tables.py",
        r"\providecommand{\asrcellTopicA}[1]{\cellcolor{green!12}#1}",
        r"\providecommand{\asrcellTopicB}[1]{\cellcolor{yellow!10}#1}",
        r"\providecommand{\asrcellTopicC}[1]{\cellcolor{red!12}#1}",
        "",
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{l|ccccc|ccccc|ccccc|ccccc|ccccc}",
        r"\hline",
        r"& \multicolumn{5}{c|}{\textbf{No Mem.}} & \multicolumn{5}{c|}{\textbf{Explicit}} & \multicolumn{5}{c|}{\textbf{Mem0}} & \multicolumn{5}{c|}{\textbf{RAG}} & \multicolumn{5}{c}{\textbf{Context}} \\",
        r"\textbf{Defense} & Fin. & Health & Legal & Tax & ID & Fin. & Health & Legal & Tax & ID & Fin. & Health & Legal & Tax & ID & Fin. & Health & Legal & Tax & ID & Fin. & Health & Legal & Tax & ID \\",
        r"\hline",
    ]
    for d_csv, d_tex in zip(DEFENSES, DEFENSE_TEX):
        lines.append(f"{d_tex} & {row_cells(data_by_topic, d_csv)} \\\\")
    lines.extend([r"\hline", r"\end{tabular}", r"}%", r"\end{table*}", ""])
    (OUT / fname).write_text("\n".join(lines), encoding="utf-8")
    print("Wrote", OUT / fname)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    write_table(
        "gemini-3.1-pro-preview",
        r"Trigger session $N=100$: attack success rate (ASR, \%) by defense, memory backend, and topic for Gemini~3.1~Pro~Preview. ``---'' denotes not applicable. Cells use light heatmap shading (low to high ASR).",
        "asr_by_topic_test_100_gemini.tex",
        "tab:asr-by-topic-gemini",
    )
    write_table(
        "gpt-5-mini",
        r"Trigger session $N=100$: attack success rate (ASR, \%) by defense, memory backend, and topic for GPT-5-mini. ``---'' denotes not applicable. Cells use light heatmap shading (low to high ASR).",
        "asr_by_topic_test_100_gpt5mini.tex",
        "tab:asr-by-topic-gpt5mini",
    )


if __name__ == "__main__":
    main()
